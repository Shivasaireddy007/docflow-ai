"""Renders an evaluation run as Markdown."""

from typing import Any

LABELS = {
    "total": "Total",
    "subtotal": "Subtotal",
    "tax": "Tax",
    "service_charge": "Service charge",
    "discount": "Discount",
}


MISSING = "–"  # noqa: RUF001  (an en dash reads as "none" in tables)


def pct(value: float | None) -> str:
    return MISSING if value is None else f"{value * 100:.0f}%"


def seconds(ms: float | None) -> str:
    return MISSING if ms is None else (f"{ms / 1000:.1f} s" if ms >= 100 else f"{ms:.0f} ms")


def render(result: dict[str, Any]) -> str:
    run, summary = result["run"], result["summary"]
    d = summary["decisions"]
    lat = summary["latency_ms"]
    lines = [
        "# Evaluation",
        "",
        f"`{run['pipeline_version']}` on {run['dataset']}, run {run['date'][:10]} on {run['machine']}.",
        "Generated by `uv run python -m evaluation.run`; raw numbers in [`results.json`](results.json).",
        "",
        "## Decisions under the default rules",
        "",
        "Judged on the total, the amount that gets paid.",
        "",
        "| | |",
        "|---|---|",
        f"| Receipts with a labelled total | {d['documents']} |",
        f"| Approved automatically | {d['auto_approved']} ({pct(d['auto_approve_rate'])}) |",
        f"| Wrong totals among them | {d['wrong_auto_approvals']} "
        f"({pct(d['auto_approval_error_rate'])} of auto-approvals) |",
        f"| Wrong totals overall | {d['wrong_totals']} |",
        f"| Wrong totals sent to a person | {d['wrong_totals_caught']} of {d['wrong_totals']} |",
        "",
        "## Choosing the confidence threshold",
        "",
        "The other default rules held fixed; only the confidence threshold varies.",
        "",
        "| Threshold | Auto-approved | Wrong totals approved | Error rate of auto-approvals |",
        "|---|---|---|---|",
    ]
    for row in summary["threshold_sweep"]:
        lines.append(
            f"| {row['threshold']:.2f} | {row['auto_approved']} ({pct(row['auto_approve_rate'])}) | "
            f"{row['wrong_auto_approvals']} | {pct(row['auto_approval_error_rate'])} |"
        )
    lines += [
        "",
        "## Field accuracy",
        "",
        "Precision: of the values extracted, the share that were right. Recall: of the values printed on",
        "the receipts, the share extracted correctly.",
        "",
        "| Field | On receipts | Extracted | Correct | Precision | Recall |",
        "|---|---|---|---|---|---|",
    ]
    for name, s in summary["fields"].items():
        lines.append(
            f"| {LABELS[name]} | {s['labelled']} | {s['extracted']} | {s['correct']} "
            f"| {pct(s['precision'])} | {pct(s['recall'])} |"
        )
    items = summary["line_items"]
    lines += [
        "",
        f"Line-item amounts: precision {pct(items['precision'])}, recall {pct(items['recall'])} "
        f"({items['matched']} matched).",
        "",
        "## Speed",
        "",
        "| | p50 | p95 |",
        "|---|---|---|",
        f"| OCR | {seconds(lat['ocr_p50'])} | {seconds(lat['ocr_p95'])} |",
        f"| Field extraction | {seconds(lat['extraction_p50'])} | {seconds(lat['extraction_p95'])} |",
        f"| Whole document | {seconds(lat['document_p50'])} | {seconds(lat['document_p95'])} |",
        f"| Whole document, cached | {seconds(lat['cached_document_p50'])} "
        f"| {seconds(lat['cached_document_p95'])} |",
        "",
        _model_time(summary["model_ms_per_document"]),
        "",
    ]
    return "\n".join(lines)


def _model_time(ms_per_document: float | None) -> str:
    if not ms_per_document:
        return ""
    hours = ms_per_document * 1000 / 1000 / 3600
    return f"Model time per 1,000 documents: about {hours:.1f} hours on this machine, one at a time."
